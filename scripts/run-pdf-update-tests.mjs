import assert from 'node:assert/strict';
import { cpSync, existsSync, mkdtempSync, mkdirSync, readFileSync, rmSync, writeFileSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
import { execFileSync } from 'node:child_process';
import { nachziehen as appKopieren } from '../tools/wfpdf-app-nachziehen.mjs';
import { nachziehen as kernKopieren, DATEIEN } from '../tools/wfpdf-nachziehen.mjs';
import { updateVorbereiten } from '../tools/pdf-update.mjs';
const temp = mkdtempSync(join(tmpdir(), 'pdf-update-test-'));
const quelle = join(temp, 'quelle'), pro = join(temp, 'pro'), fa = join(temp, 'fa');
const git = (cwd, ...args) => execFileSync('git', args, { cwd, encoding: 'utf8', stdio: ['ignore', 'pipe', 'pipe'] }).trim();
const put = (p, v) => { mkdirSync(join(p, '..'), { recursive: true }); writeFileSync(p, v); };
const init = p => { mkdirSync(p, { recursive: true }); git(p, 'init'); git(p, 'config', 'user.name', 'Probe'); git(p, 'config', 'user.email', 'probe@example.invalid'); };
const commit = p => { git(p, 'add', '.'); git(p, 'commit', '-m', 'Erfundener Stand'); };
const proSync = () => { rmSync(join(pro, 'upstream/workflow-pdf'), { recursive: true, force: true }); cpSync(quelle, join(pro, 'upstream/workflow-pdf'), { recursive: true, filter: p => !p.split('/').includes('.git') }); commit(pro); };
try {
  init(quelle); init(pro);
  for (const [, p] of DATEIEN) put(join(quelle, p), '// erfundener Baustein');
  put(join(quelle, 'assets/erkennung.js'), 'window.WFP={Erkennung:{schonBelegt(){return ""}}};');
  put(join(quelle, 'assets/app.js'), '// erfundene Bedienung');
  put(join(quelle, 'assets/style.css'), 'body{color:teal}');
  put(join(quelle, 'index.html'), '<html><head><meta charset="utf-8"><script defer src="assets/sbkim-init.js?v=1"></script></head><body><script>if(\'serviceWorker\' in navigator&&location.protocol===\'https:\')navigator.serviceWorker.register(\'sw.js\').catch(function(){});</script></body></html>');
  commit(quelle); proSync();
  const app = appKopieren(quelle, fa), kern = kernKopieren(quelle, fa);
  put(join(fa, 'public/apps/HERKUNFT.json'), JSON.stringify({ apps: { 'workflow-pdf': app } }));
  put(join(fa, 'public/wfpdf/HERKUNFT.json'), JSON.stringify(kern));
  put(join(fa, 'public/apps/fa-wfpdf-bruecke.js'), 'eigene Brücke');
  put(join(fa, 'public/apps/fa-wfpdf-thema.css'), 'eigene Gestaltung');
  put(join(fa, 'private-dokumente.txt'), 'erfundene private Datei');
  assert.equal(updateVorbereiten(quelle, pro, fa, true).updateVorhanden, false);
  put(join(fa, 'public/apps/workflow-pdf/eigene-notiz.txt'), 'Eigene Notiz');
  assert.throws(() => updateVorbereiten(quelle, pro, fa, true), /Zusätzliche lokale Datei/);
  rmSync(join(fa, 'public/apps/workflow-pdf/eigene-notiz.txt'));
  put(join(quelle, 'assets/scanner.js'), '// Funktionsverbesserung'); commit(quelle);
  assert.throws(() => updateVorbereiten(quelle, pro, fa, true), /anderen PDF-Kern/);
  assert.equal(readFileSync(join(fa, 'public/wfpdf/scanner.js'), 'utf8'), '// erfundener Baustein');
  proSync();
  assert.equal(updateVorbereiten(quelle, pro, fa).angewendet, false);
  assert.equal(readFileSync(join(fa, 'public/wfpdf/scanner.js'), 'utf8'), '// erfundener Baustein');
  assert.equal(updateVorbereiten(quelle, pro, fa, true).angewendet, true);
  assert.equal(readFileSync(join(fa, 'public/wfpdf/scanner.js'), 'utf8'), '// Funktionsverbesserung');
  assert.equal(readFileSync(join(fa, 'public/apps/workflow-pdf/assets/scanner.js'), 'utf8'), '// Funktionsverbesserung');
  assert.equal(readFileSync(join(fa, 'public/apps/fa-wfpdf-bruecke.js'), 'utf8'), 'eigene Brücke');
  assert.equal(readFileSync(join(fa, 'public/apps/fa-wfpdf-thema.css'), 'utf8'), 'eigene Gestaltung');
  assert.equal(readFileSync(join(fa, 'private-dokumente.txt'), 'utf8'), 'erfundene private Datei');
  // Counterexample: updated style must not silently slip through the normal copier.
  put(join(quelle, 'assets/style.css'), 'body{color:red}'); commit(quelle); proSync();
  assert.throws(() => updateVorbereiten(quelle, pro, fa, true), /Design-\/Inhaltsänderung/);
  assert.equal(readFileSync(join(fa, 'public/apps/workflow-pdf/assets/style.css'), 'utf8'), 'body{color:teal}');
  put(join(quelle, 'assets/style.css'), 'body{color:teal}');
  put(join(quelle, 'assets/erkennung.js'), 'window.WFP={Erkennung:{}};'); commit(quelle); proSync();
  assert.throws(() => updateVorbereiten(quelle, pro, fa, true), /Funktionsvertrag/);
  assert.ok(readFileSync(join(fa, 'public/wfpdf/erkennung.js'), 'utf8').includes('schonBelegt'));
  put(join(fa, 'public/wfpdf/scanner.js'), '// lokale Änderung');
  assert.throws(() => updateVorbereiten(quelle, pro, fa, true), /Lokaler Kern geändert/);
  assert.ok(existsSync(join(fa, 'private-dokumente.txt')));
  console.log('PDF-Update: echter Kopierweg, beide Kopien, Vorschau, Pro-Gleichstand, unveränderte Brücke/Gestaltung/Daten, Design-Gegenprobe, fehlende API und lokale Änderungen geprüft.');
} finally { rmSync(temp, { recursive: true, force: true }); }
