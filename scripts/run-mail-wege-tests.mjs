// 2.28.65: E-Mail-Wege – Wahl, Gesundheitswort (nur Hinweis), Anlagen-Grenzen, Adressen, ehrliche Microsoft-Meldungen.
import assert from "node:assert/strict";
const m = await import("../lib/mail-wege.ts");
let n = 0; const gruen = (t) => { n++; console.log(`🟢 ${t}`); };
assert.deepEqual(m.wahlLesen(null), m.MAIL_VORGABE);
assert.equal(m.MAIL_VORGABE.empfang, "brain"); assert.equal(m.MAIL_VORGABE.versand, "mailapp"); assert.equal(m.MAIL_VORGABE.brainAuto, true);
assert.deepEqual(m.wahlLesen(JSON.stringify({ empfang: "microsoft", versand: "microsoft", brainAuto: false })), { empfang: "microsoft", versand: "microsoft", brainAuto: false });
assert.equal(m.wahlLesen(JSON.stringify({ empfang: "eigen" })).empfang, "brain", "geplanter Weg ist nicht wählbar");
assert.equal(m.wahlLesen("kaputt").empfang, "brain");
gruen("Wahl: Vorgabe Private Brain + Mail-App + von selbst abholen; „eigenes Mail-Programm“ (geplant) nicht wählbar");
assert.equal(m.gesundheitswort("Befund vom 03.11."), "Befund");
assert.equal(m.gesundheitswort("Anfrage zur Rechnung"), null);
assert.equal(m.gesundheitswort("Termin Praxis Dr. Muster"), "Praxis");
gruen("e2: Gesundheitswort im Betreff erkannt (Gegenprobe: neutraler Betreff ohne Hinweis)");
assert.equal(m.anlagenPruefen([10e6, 9e6], "mailapp").ok, true);
assert.equal(m.anlagenPruefen([15e6, 9e6], "mailapp").ok, false);
assert.match(m.anlagenPruefen([4e6], "microsoft").satz, /größer als 3 MB/);
assert.equal(m.anlagenPruefen([2e6], "microsoft").ok, true);
gruen("e3: Anlagen über 20 MB → Ansage; Microsoft je Anlage höchstens 3 MB, sonst ehrlich auf die Mail-App verweisen");
assert.deepEqual(m.adressen("a@beispiel.invalid, b@beispiel.invalid"), ["a@beispiel.invalid", "b@beispiel.invalid"]);
assert.equal(m.adressen("Praxis Muster"), null); assert.equal(m.adressen(""), null);
assert.match(m.mailtoAdresse("a@beispiel.invalid", "Anfrage zu Unterlagen", "Guten Tag"), /^mailto:a@beispiel\.invalid\?subject=Anfrage%20zu%20Unterlagen&body=Guten%20Tag$/);
gruen("Empfänger nur als Adresse; mailto mit Betreff und Text");
assert.match(m.microsoftFehler(403, "ErrorAccessDenied"), /Mail\.Read und Mail\.Send.*noch nicht eingerichtet/);
assert.match(m.microsoftFehler(401, ""), /abgelaufen/);
assert.match(m.microsoftFehler(500, "X"), /abgelehnt \(500, X\)/);
gruen("e10: fehlende Rechte in Entra werden ehrlich gemeldet, nicht verschwiegen");
assert.equal(m.emlName("Rechnung: Oktober/2026", "2026-11-02T08:00:00Z"), "2026-11-02 Rechnung Oktober 2026.eml");
gruen("Abgeholte Mail heißt „Datum Betreff.eml“");
console.log(`\n${n} Gruppen grün.`);
